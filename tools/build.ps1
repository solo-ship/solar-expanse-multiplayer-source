# The shim pin (M4, I-8): src\Core\Join\ShimPin.g.cs (generated, git-ignored) holds the SHA-256 of the BepInEx shim built with the
# main DLL, and is compiled into the main DLL, so only that shim passes the content check. Six passes, all /deterministic+:
#   1 write a placeholder ShimPin.g.cs if it is missing; 2 build the main DLL (pass 1); 3 build the shim against it;
#   4 hash the shim and write the hash into ShimPin.g.cs; 5 build the main DLL again (pass 2) and, from the same file, the
#   desktop builds; 6 build the shim again against the pass 2 DLL and compare its hash with the pin: any difference fails the build.
# Builds the mod DLL and the BepInEx shim with the VS Build Tools Roslyn compiler. Also compiles the mod against BepInEx's
# HarmonyX (a check only: that output is thrown away). In the full development tree it then builds the offline test tools
# and the test runner and runs the tests; each of those steps is skipped when its folder (tools\..., tests\) is absent,
# as in the public source snapshot, whose test suite is kept private.
param(
    # the game folder (read only): the build compiles against its Solar Expanse_Data\Managed DLLs
    [string]$GameRoot = $(if ($env:SEMP_GAME_ROOT) { $env:SEMP_GAME_ROOT } else { "C:\Program Files (x86)\Steam\steamapps\common\Solar Expanse" }),
    # optional: a game folder with BepInEx 5.4.23.5; its BepInEx\core\0Harmony.dll is HarmonyX 2.9, the Harmony a BepInEx player has
    [string]$BepInExRoot = $env:SEMP_BEPINEX_ROOT,
    [switch]$NoTests,
    [string]$TestFilter = ""                 # run only the tests whose Class.Method contains this (the full suite when empty)
)
$ErrorActionPreference = "Stop"
$repo = Split-Path $PSScriptRoot -Parent
$lib  = Join-Path $repo "lib"
$bin  = Join-Path $repo "bin"
$managed = Join-Path $GameRoot "Solar Expanse_Data\Managed"
if (-not (Test-Path (Join-Path $managed "Assembly-CSharp.dll"))) { throw "No game DLLs in $managed" }
foreach ($f in "harmony\0Harmony.dll", "bepinex\BepInEx.dll") {
    if (-not (Test-Path (Join-Path $lib $f))) { throw "Missing lib\$f - run tools\fetch-deps.ps1" }
}

$csc = "C:\Program Files (x86)\Microsoft Visual Studio\18\BuildTools\MSBuild\Current\Bin\Roslyn\csc.exe"
if (-not (Test-Path $csc)) {
    $found = Get-ChildItem "C:\Program Files*\Microsoft Visual Studio" -Recurse -Filter csc.exe -ErrorAction SilentlyContinue |
             Where-Object { $_.FullName -like "*\Roslyn\csc.exe" } | Select-Object -First 1
    if ($found) { $csc = $found.FullName } else { throw "Roslyn csc.exe not found - install Visual Studio Build Tools." }
}
New-Item -ItemType Directory -Force $bin | Out-Null

function Invoke-Csc([string[]]$cscArgs, [string]$name) {
    # a response file (the reference list is past Windows' command-line limit), unique so two builds never share one
    $rsp = Join-Path $env:TEMP ("semp-$name-" + [Guid]::NewGuid().ToString("N") + ".rsp")
    try {
        ($cscArgs | ForEach-Object { '"' + $_ + '"' }) | Set-Content -Path $rsp -Encoding ASCII
        & $csc "/noconfig" ("@" + $rsp)
        if ($LASTEXITCODE -ne 0) { throw "csc failed for $name (exit $LASTEXITCODE)" }
    } finally { Remove-Item $rsp -ErrorAction SilentlyContinue }
}
function Sources([string[]]$dirs) {
    $dirs | ForEach-Object { $d = Join-Path $repo $_; if (Test-Path $d) { Get-ChildItem $d -Filter *.cs -Recurse | ForEach-Object { $_.FullName } } }
}

$gameRefs = Get-ChildItem $managed -Filter *.dll | ForEach-Object { "/reference:" + $_.FullName }
$common   = @("/nostdlib+", "/optimize+", "/langversion:7.3", "/nologo", "/warn:4", "/deterministic+")
$modSrc   = Sources @("src\Core", "src\Net", "src\Loader", "src\Game")

$mainDll = Join-Path $bin "SolarExpanseMultiplayer.dll"
$shimSrc = Sources @("src\BepInExShim")
$shimDll = Join-Path $bin "SolarExpanseMultiplayer.BepInEx.dll"
$pinFile = Join-Path $repo "src\Core\Join\ShimPin.g.cs"
function Write-ShimPin([string]$hash) {
    $text = "// Generated by tools\build.ps1 (the shim pin, I-8). Not committed: do not edit.`r`nnamespace SolarExpanseMultiplayer`r`n{`r`n" +
            "    public static class ShimPin { public const string Sha256 = `"$hash`"; }`r`n}`r`n"
    [IO.File]::WriteAllText($pinFile, $text, (New-Object Text.UTF8Encoding($false)))
}
# pass 1 of the pin: a placeholder when the file is missing (it never matches a real shim, so it fails closed)
if (-not (Test-Path $pinFile)) { New-Item -ItemType Directory -Force (Split-Path $pinFile -Parent) | Out-Null; Write-ShimPin ("0" * 64) }
$modSrc = Sources @("src\Core", "src\Net", "src\Loader", "src\Game")   # again: the pin file may have just been made

# pass 2: the main DLL, with whatever pin is there
Invoke-Csc ($common + @("/target:library", ("/out:" + $mainDll), ("/reference:" + (Join-Path $lib "harmony\0Harmony.dll"))) +
            $gameRefs + $modSrc) "main"
if ($shimSrc) {
    # pass 3: the shim against it; pass 4: its hash goes into ShimPin.g.cs
    Invoke-Csc ($common + @("/target:library", ("/out:" + $shimDll), ("/reference:" + (Join-Path $lib "bepinex\BepInEx.dll")),
                ("/reference:" + $mainDll)) + $gameRefs + $shimSrc) "shim"
    $shimPin = (Get-FileHash -Algorithm SHA256 -Path $shimDll).Hash.ToLowerInvariant()
    Write-ShimPin $shimPin
    # pass 5 (main DLL pass 2): the real pin is compiled in; the desktop builds below use the same file
    Invoke-Csc ($common + @("/target:library", ("/out:" + $mainDll), ("/reference:" + (Join-Path $lib "harmony\0Harmony.dll"))) +
                $gameRefs + $modSrc) "main-pass2"
}

# The same sources against HarmonyX (BepInEx's Harmony): catches an API our Harmony 2.4 has and HarmonyX lacks.
$harmonyX = if ($BepInExRoot) { Join-Path $BepInExRoot "BepInEx\core\0Harmony.dll" } else { "" }
if ($harmonyX -and (Test-Path $harmonyX)) {
    $checkDir = Join-Path $env:TEMP ("semp-harmonyx-" + [Guid]::NewGuid().ToString("N"))
    New-Item -ItemType Directory -Force $checkDir | Out-Null
    try {
        Invoke-Csc ($common + @("/target:library", ("/out:" + (Join-Path $checkDir "check.dll")), ("/reference:" + $harmonyX)) +
                    $gameRefs + $modSrc) "harmonyx"
        Write-Host "HarmonyX check OK ($harmonyX)"
    } finally { Remove-Item $checkDir -Recurse -Force -ErrorAction SilentlyContinue }
} else { Write-Warning "No HarmonyX (give -BepInExRoot or set SEMP_BEPINEX_ROOT) - skipped the BepInEx compile check." }

if ($shimSrc) {
    # pass 6: the shim again, against the pass 2 main DLL, to a throwaway path: it must hash exactly as the pin says
    # (the same file name in a folder of its own: the module name is part of what is hashed)
    $shimDir2 = Join-Path $env:TEMP ("semp-shim2-" + [Guid]::NewGuid().ToString("N"))
    New-Item -ItemType Directory -Force $shimDir2 | Out-Null
    try {
        $shim2 = Join-Path $shimDir2 (Split-Path $shimDll -Leaf)
        Invoke-Csc ($common + @("/target:library", ("/out:" + $shim2), ("/reference:" + (Join-Path $lib "bepinex\BepInEx.dll")),
                    ("/reference:" + $mainDll)) + $gameRefs + $shimSrc) "shim-pass6"
        $second = (Get-FileHash -Algorithm SHA256 -Path $shim2).Hash.ToLowerInvariant()
    } finally { Remove-Item $shimDir2 -Recurse -Force -ErrorAction SilentlyContinue }
    # the pin is read back from the file the main DLL was compiled from, not from the variable
    $pinned = ([regex]::Match([IO.File]::ReadAllText($pinFile), '[0-9a-f]{64}')).Value
    Write-Host ("Shim pin: " + $pinned + "; second shim build: " + $second + "; " + $(if ($second -eq $pinned) { "match" } else { "MISMATCH" }))
    if ($second -ne $pinned) { throw "The shim built against the final main DLL differs from the pinned one: the pin would not match the shim that ships." }
}

# Desktop .NET Framework builds (tests, fake client): Core and Net code must only use APIs both runtimes have.
# They use the game's Newtonsoft.Json (netstandard 2.0), copied beside them in bin\ (never committed, never shipped).
$fw = "C:\Windows\Microsoft.NET\Framework64\v4.0.30319"
$newtonsoft = Join-Path $managed "Newtonsoft.Json.dll"
$hasTests = Test-Path (Join-Path $repo "tests")
$hasDesktop = $hasTests -or @("tools\fakeclient", "tools\driftcompare", "tools\savescan", "tools\patchcheck" |
              Where-Object { Test-Path (Join-Path $repo $_) }).Count -gt 0
if ($hasDesktop) { Copy-Item $newtonsoft $bin -Force }
$deskRefs = @(("/reference:" + (Join-Path $fw "System.dll")), ("/reference:" + (Join-Path $fw "System.Core.dll")),
              ("/reference:" + (Join-Path $fw "netstandard.dll")), ("/reference:" + $newtonsoft))

$fakeSrc = Sources @("tools\fakeclient")
if ($fakeSrc) {
    Invoke-Csc (@("/optimize+", "/langversion:7.3", "/nologo", "/warn:4", "/target:exe", ("/out:" + (Join-Path $bin "SempFakeClient.exe"))) +
                $deskRefs + (Sources @("src\Core", "src\Net")) + $fakeSrc) "fakeclient"
}

# The offline drift comparer: Core (the analysis, the file reader) and the tool. Its --selftest runs the analysis and cost gate
# tests, so those test files (and the runner, which has no Main of its own here) are compiled in; the tool's Main is the entry.
$compareDir = Join-Path $repo "tools\driftcompare"
if (Test-Path $compareDir) {
    $selfTestSrc = @("Runner.cs", "TempDir.cs", "DriftAnalysisTests.cs", "CostGateTests.cs") | ForEach-Object { Join-Path $repo ("tests\" + $_) }
    Invoke-Csc (@("/optimize+", "/langversion:7.3", "/nologo", "/warn:4", "/target:exe", "/main:SolarExpanseMultiplayer.DriftCompareTool", ("/out:" + (Join-Path $bin "SempDriftCompare.exe"))) +
                $deskRefs + (Sources @("src\Core", "tools\driftcompare")) + $selfTestSrc) "driftcompare"
}

# The offline save scanner (M4 Task 7, bin\SempSaveScan.exe): Core (OdinScan, the type-name grammar, the allowlist) and the tool.
$scanDir = Join-Path $repo "tools\savescan"
if (Test-Path $scanDir) {
    Invoke-Csc (@("/optimize+", "/langversion:7.3", "/nologo", "/warn:4", "/target:exe", "/main:SolarExpanseMultiplayer.SaveScanTool", ("/out:" + (Join-Path $bin "SempSaveScan.exe"))) +
                $deskRefs + (Sources @("src\Core", "tools\savescan"))) "savescan"
}

# The offline patch check (M5 Task 8, bin\SempPatchCheck.exe; tools\patch-check.ps1 runs it): applies the mod's patch classes to the
# real game DLL with Harmony 2.4.2 and HarmonyX. It loads the mod DLL and Harmony from its own folder, so it compiles against lib\
# Harmony only. The runtimeconfig lets the same exe run on .NET 8 for its --dry mode.
$patchCheckDir = Join-Path $repo "tools\patchcheck"
if (Test-Path $patchCheckDir) {
    Invoke-Csc (@("/optimize+", "/langversion:7.3", "/nologo", "/warn:4", "/target:exe", ("/out:" + (Join-Path $bin "SempPatchCheck.exe")),
                  ("/reference:" + (Join-Path $lib "harmony\0Harmony.dll"))) + $deskRefs + (Sources @("tools\patchcheck"))) "patchcheck"
    Set-Content -Path (Join-Path $bin "SempPatchCheck.runtimeconfig.json") -Encoding ASCII -Value '{"runtimeOptions":{"tfm":"net8.0","framework":{"name":"Microsoft.NETCore.App","version":"8.0.0"}}}'
}

if (-not $NoTests -and -not $hasTests) { Write-Host "No tests\ folder here: the test build and run were skipped." }
if (-not $NoTests -and $hasTests) {
    # The tests also compile the comparer's tool and the save scanner's tool (their command lines are tested), so the runner is named as the entry.
    $testExe = Join-Path $bin "SempTests.exe"
    Invoke-Csc (@("/optimize+", "/langversion:7.3", "/nologo", "/warn:4", "/target:exe", "/main:SolarExpanseMultiplayer.Tests.Runner", ("/out:" + $testExe)) +
                $deskRefs + (Sources @("src\Core", "src\Net", "tests", "tools\driftcompare", "tools\savescan"))) "tests"
    if ($TestFilter) { & $testExe $TestFilter } else { & $testExe }
    if ($LASTEXITCODE -ne 0) { throw "Tests failed" }
    # The fake client's join self-tests (M4 Task 12): in process over loopback, about 15 s. Not with -TestFilter, so a
    # mutation run of another set does not pay for them on every mutant; tools\test-fakeclient.ps1 runs them alone.
    if (-not $TestFilter) {
        & (Join-Path $repo "tools\test-fakeclient.ps1") -NoBuild -Only selftests
        if ($LASTEXITCODE -ne 0) { throw "The fake client's join self-tests failed" }
    }
}
Write-Host "Build OK: $bin"
